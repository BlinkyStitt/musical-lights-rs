#!/usr/bin/env python3
"""Build the bundled HYG 4.1 subset from its pinned, separately downloaded CSV."""

import argparse
import csv
import hashlib
import json
import math
from pathlib import Path

REVISION = "c7f7f883fe678cc7680169a50ccd7dcc49b060ce"
SOURCE_SHA256 = "d9f69fd86bbf90a4e4d52b4c5c53eacfa6dfc0bfdef85bfd94f095e0bebe4ebd"
SOURCE = f"https://raw.githubusercontent.com/astronexus/HYG-Database/{REVISION}/hyg/CURRENT/hygdata_v41.csv"
OUTPUT = (
    Path(__file__).resolve().parents[1] / "musical-leptos/src/physics/stars-catalog.js"
)


def generate(source):
    if hashlib.sha256(source.read_bytes()).hexdigest() != SOURCE_SHA256:
        raise ValueError("The input is not the pinned HYG 4.1 catalog")
    rows = []
    with source.open(newline="") as stream:
        for row in csv.DictReader(stream):
            identity = int(row["id"])
            ra, dec, magnitude = (float(row[key]) for key in ("ra", "dec", "mag"))
            if identity == 0 or magnitude > 6.5:
                continue
            if not all(math.isfinite(v) for v in (ra, dec, magnitude)):
                raise ValueError("Invalid catalog coordinates or magnitude")
            if not 0 <= ra < 24 or not -90 <= dec <= 90:
                raise ValueError("Catalog coordinate outside its domain")
            color = float(row["ci"]) if row["ci"] else None
            if color is not None and not math.isfinite(color):
                raise ValueError("Invalid catalog color index")
            rows.append([identity, ra, dec, magnitude, color])
    header = (
        "// Generated by validation/generate-stars.py. Data: HYG 4.1, David Nash / Astronexus.\n"
        "// CC-BY-SA-4.0: https://creativecommons.org/licenses/by-sa/4.0/\n"
        "// Adaptation: Sun excluded; apparent V magnitude <= 6.5; selected fields only.\n"
        "// Each row: HYG id, J2000 RA hours, J2000 declination degrees, V magnitude, B-V or null.\n"
        f"export const CATALOG_SOURCE = '{SOURCE}';\n"
        f"export const CATALOG_SHA256 = '{SOURCE_SHA256}';\n"
        "export const CATALOG = [\n"
    )
    return (
        header
        + "".join(json.dumps(row, separators=(",", ":")) + ",\n" for row in rows)
        + "];\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate(args.source)
    if args.check:
        if OUTPUT.read_text() != generated:
            raise ValueError("Bundled star catalog is out of date")
    else:
        OUTPUT.write_text(generated)


if __name__ == "__main__":
    main()
